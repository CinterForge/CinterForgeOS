    def test_smoke_uses_guest_nethernet_marker_and_sequenced_console(self):
        with tempfile.TemporaryDirectory() as td:
            root=Path(td); boot=root/'boot'; server=root/'server'; boot.mkdir(); server.mkdir()
            runner=boot/'run-mac-bds.sh'
            runner.write_text("#!/bin/sh\necho CINTER_BDS_NETHERNET_PASS\necho '[2026-09-20 20:17:53:730 INFO] Server started.'\nwhile IFS= read -r line; do\n  case \"$line\" in\n    list) echo 'There are 0/10 players online' ;;\n    stop) echo 'Server stop requested.'; echo 'Stopping server...'; echo 'Quit correctly'; echo 'CINTER_BDS_EXIT rc=0'; exit 0 ;;\n  esac\ndone\n")
            runner.chmod(0o755)
            proof=smoke(boot, server, startup_timeout=2)
            self.assertEqual(proof['status'],'pass')
            self.assertEqual(proof['network_probe'],'guest-local-nethernet-tcp')
            self.assertTrue(proof['console_response_verified'])
            self.assertTrue(proof['graceful_stop'])
            source=(Path(__file__).resolve().parent.parent / 'craftmaster' / 'craftmaster_mac_bootstrap.py').read_text()
            self.assertIn("if 'Server started.' in line: server_started=True", source)
            self.assertIn('if network and server_started and (rosetta or not require_cfos_rosetta): break', source)
            self.assertIn("p.stdin.write('list\\n'); p.stdin.flush()", source)
            self.assertIn("p.stdin.write('stop\\n'); p.stdin.flush()", source)
            self.assertNotIn("p.stdin.write('list\\nstop\\n')", source)
            self.assertLess(source.index("p.stdin.write('list\\n')"), source.index("if not list_ok:"))
            self.assertLess(source.index("if not list_ok:"), source.index("p.stdin.write('stop\\n')"))

