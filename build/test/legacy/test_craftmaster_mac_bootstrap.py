    def test_smoke_temporarily_disables_online_mode_and_restores_properties(self):
        with tempfile.TemporaryDirectory() as td:
            root=Path(td); boot=root/'boot'; server=root/'server'; boot.mkdir(); server.mkdir()
            original=b'server-name=Cinter Test\nonline-mode=true\nserver-port=19132\n'
            props=server/'server.properties'; props.write_bytes(original)
            runner=boot/'run-mac-bds.sh'
            runner.write_text("#!/bin/sh\ngrep -q '^online-mode=false$' \"$1/server.properties\" || exit 9\ngrep -q '^enable-lan-visibility=true$' \"$1/server.properties\" || exit 10\necho CINTER_BDS_NETHERNET_PASS\necho '[2026-09-20 20:17:53:730 INFO] Server started.'\nwhile IFS= read -r line; do\n  case \"$line\" in\n    list) echo 'There are 0/10 players online' ;;;;\n    stop) echo 'Server stop requested.'; echo 'Stopping server...'; echo 'Quit correctly'; echo 'CINTER_BDS_EXIT rc=0'; exit 0 ;;;;\n  esac\ndone\n".replace(';;;;',';;'))
