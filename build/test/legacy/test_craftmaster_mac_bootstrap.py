    def test_cfos_smoke_requires_rosetta_and_preserves_server_properties(self):
        with tempfile.TemporaryDirectory() as td:
            root = Path(td); server = root / 'server'; server.mkdir()
            props = server / 'server.properties'
            original = b'online-mode=true\nserver-name=Cinter Test\n'
            props.write_bytes(original)
            runner = root / 'run-cfos-fake.sh'
            runner.write_text(
                "#!/bin/sh\n"
                "echo CINTER_BDS_NETHERNET_PASS\n"
                "echo 'Server started.'\n"
                "while IFS= read -r line; do\n"
                " case \"$line\" in\n"
                " list) echo 'There are 0/10 players online' ;;\n"
                " stop) echo 'Server stop requested.'; echo 'Stopping server...'; echo 'Quit correctly'; echo 'CINTER_BDS_EXIT rc=0'; exit 0 ;;\n"
                " esac\n"
                "done\n")
            runner.chmod(0o755)
            with self.assertRaisesRegex(RuntimeError, 'rosetta=False'):
                smoke(None, server, startup_timeout=.5, launcher_command=[str(runner)])
            self.assertEqual(props.read_bytes(), original)
            runner.write_text(runner.read_text().replace(
                'echo CINTER_BDS_NETHERNET_PASS',
                'echo CINTER_BDS_ROSETTA_REGISTERED\necho CINTER_BDS_NETHERNET_PASS'))
            proof = smoke(None, server, startup_timeout=2, launcher_command=[str(runner)])
            self.assertEqual(proof['status'], 'pass')
            self.assertTrue(proof['rosetta_registered'])
            self.assertTrue(proof['graceful_stop'])
            self.assertEqual(props.read_bytes(), original)

